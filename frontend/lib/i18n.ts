export const STRINGS: Record<Lang, typeof en> = { en, bn };

export function savedLang(): Lang {
  if (typeof window === "undefined") return "en";
  const saved = window.localStorage.getItem("xpay-lang");
  return saved === "bn" ? "bn" : "en";
}

export function applyDocLang(lang: Lang) {
  if (typeof document !== "undefined") document.documentElement.lang = lang === "bn" ? "bn" : "en";
}
